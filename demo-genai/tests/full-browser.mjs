import { launchBrowser } from '../../scripts/browser.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser=await launchBrowser({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:1440,height:1100},reducedMotion:'reduce',recordVideo:{dir:'demo-genai/captures/video',size:{width:1440,height:1100}}});
const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const cues=[];let started=performance.now();
const cue=text=>{cues.push({seconds:(performance.now()-started)/1000,text});console.log(text);};
const pause=()=>page.waitForTimeout(2400);
const waitRun=()=>page.waitForFunction(()=>window.__genai?.state.run && !window.__genai.state.busy,{timeout:300000});
await page.goto('http://127.0.0.1:4176/materials/demo-genai/?device=wasm');
started=performance.now();cue('I load the real model from this computer. No remote API is used.');
await page.click('#load');
await page.waitForFunction(()=>window.__genai?.state.model || document.getElementById('status').classList.contains('error'),{timeout:300000});
assert.ok(await page.evaluate(()=>!!window.__genai.state.model),await page.locator('#status').innerText());
cue('I analyze the starting text. Tokens and probabilities come from the model.');
await page.click('#analyze');await waitRun();await pause();
const a=await page.evaluate(()=>structuredClone(window.__genai.state.run));
await page.screenshot({path:'public/materials/demo-genai/captures/real-analysis.png',fullPage:true});
await page.click('#save');
cue('I save A, then change only temperature, from 0.8 to 1.5.');
await page.locator('#temperature').evaluate(el=>{el.value='1.5';el.dispatchEvent(new Event('input',{bubbles:true}));});
const b=await page.evaluate(()=>structuredClone(window.__genai.state.run));
assert.equal(a.top[0].id,b.top[0].id);assert.ok(b.entropyBits>a.entropyBits);assert.ok(b.top[0].probability<a.top[0].probability);
await pause();await page.click('#save');
await page.locator('#comparison-title').scrollIntoViewIfNeeded();cue('Probabilities spread out; the most likely token keeps its top rank.');await pause();
await page.screenshot({path:'public/materials/demo-genai/captures/real-temperature-comparison.png',fullPage:true});
cue('Now I change context: France instead of Italy. Temperature returns to 0.8.');
await page.locator('#temperature').evaluate(el=>{el.value='0.8';el.dispatchEvent(new Event('input',{bubbles:true}));});
await page.click('[data-example="The capital of France is"]');await page.click('#analyze');await waitRun();await pause();
const c=await page.evaluate(()=>structuredClone(window.__genai.state.run));
assert.notDeepEqual(a.top.map(x=>x.probability),c.top.map(x=>x.probability));
assert.notDeepEqual(a.tokenIds,c.tokenIds);
cue('I sample one token from the full vocabulary. The generated text joins the context.');
await page.click('#one');await waitRun();
assert.equal(await page.evaluate(()=>window.__genai.state.generated.length),1);await pause();
await page.screenshot({path:'public/materials/demo-genai/captures/real-generation.png',fullPage:true});
cue('I generate a short continuation. I can stop subsequent steps.');
await page.fill('#max-tokens','3');await page.click('#generate');await waitRun();await pause();
assert.ok(await page.evaluate(()=>window.__genai.state.generated.length>=1 && window.__genai.state.generated.length<=4));
const d=await page.evaluate(()=>structuredClone(window.__genai.state.run));
const sum=await page.evaluate(()=>window.__genai.state.probabilities.reduce((sum,p)=>sum+p,0));assert.ok(Math.abs(sum-1)<1e-10);
await page.fill('#max-tokens','24');await page.click('#generate');await page.waitForTimeout(350);await page.click('#stop');await page.waitForFunction(()=>!window.__genai.state.busy,{timeout:300000});
const stoppedCount=await page.evaluate(()=>window.__genai.state.generated.length);assert.ok(stoppedCount<24,'Stopping must happen before 24 new tokens');
cue('I reset the results. The model stays loaded in memory.');
await page.click('#reset');assert.equal(await page.evaluate(()=>window.__genai.state.generated.length),0);assert.ok(await page.evaluate(()=>!!window.__genai.state.model));await pause();
cue('Real recording. High probability does not mean a true fact.');await pause();
const end=(performance.now()-started)/1000;
const video=page.video();await context.close();await video.saveAs('public/materials/demo-genai/demo-reale.webm');
await fs.writeFile('demo-genai/captures/verified-results.json',JSON.stringify({verifiedAt:new Date().toISOString(),backend:'Chromium CPU/WASM',a,b,c,d,probabilitySum:sum,stoppedCount,errors},null,2));
function time(s){const ms=Math.round(s*1000);return `${String(Math.floor(ms/3600000)).padStart(2,'0')}:${String(Math.floor(ms/60000)%60).padStart(2,'0')}:${String(Math.floor(ms/1000)%60).padStart(2,'0')}.${String(ms%1000).padStart(3,'0')}`;}
const vtt='WEBVTT\n\n'+cues.map((item,i)=>`${i+1}\n${time(item.seconds)} --> ${time(cues[i+1]?.seconds??end)}\n${item.text}\n`).join('\n');
await fs.writeFile('public/materials/demo-genai/demo-reale.en.vtt',vtt);
await fs.writeFile('public/materials/demo-genai/trascrizione-demo.txt','REAL RECORDING — local inference Qwen2.5-0.5B-Instruct q4\n\n'+cues.map(x=>`${time(x.seconds)}  ${x.text}`).join('\n\n')+'\n');
assert.deepEqual(errors,[]);
await browser.close();
console.log(JSON.stringify({seconds:end,a:a.top[0],b:b.top[0],contextChanged:true,generated:d.output,stoppedCount,errors},null,2));
